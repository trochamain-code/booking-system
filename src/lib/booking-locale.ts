export type MessageKey = keyof typeof messages.es;
export function translator(language: unknown) {
  const lang = bookingLanguage(language);
  return (key: MessageKey, values: Record<string, string | number> = {}): string =>
    messages[lang][key].replace(/\{(\w+)\}/g, (match, name) => String(values[name] ?? match));
}
export function money(cents: number, language: unknown): string {
  return new Intl.NumberFormat(intlLocale[bookingLanguage(language)], { style: "currency", currency: "EUR" }).format(cents / 100);
}

