export const languages = ["es", "en", "fr", "it"] as const;
export type BookingLanguage = typeof languages[number];
export function bookingLanguage(value: unknown): BookingLanguage {
  if (typeof value !== "string") return "es";
  const base = value.toLowerCase().split(/[-_]/)[0];
  return languages.includes(base as BookingLanguage) ? base as BookingLanguage : "es";
}
